# Speed. Two small in-memory caches. "default" is used by the sign-in lock.
# "snap" holds numbers every page shows (the open request count, the home page
# totals) and the "has anyone missed a deadline" check for a few seconds, so
# they are not recomputed on every click or poll. While tests run "snap" does
# nothing, so every test sees fresh data.
_LOCMEM = "django.core.cache.backends.locmem.LocMemCache"
CACHES = {
    "default": {"BACKEND": _LOCMEM, "LOCATION": "blood-network"},
    "snap": {
        "BACKEND": "django.core.cache.backends.dummy.DummyCache" if "test" in sys.argv else _LOCMEM,
        "LOCATION": "blood-network-snap",
    },
}

# Signing in checks the password with PBKDF2. Django's default is very heavy for
# the small shared CPU on a free host (about 1.5 million rounds). 600,000 rounds
# is the current OWASP advice, still strong, and about 2.5x faster. Passwords
# saved with the old setting keep working and are upgraded on the next sign-in.
PASSWORD_HASHERS = [
    "core.hashers.FastPBKDF2PasswordHasher",
    "django.contrib.auth.hashers.PBKDF2PasswordHasher",
    "django.contrib.auth.hashers.PBKDF2SHA1PasswordHasher",
    "django.contrib.auth.hashers.Argon2PasswordHasher",
    "django.contrib.auth.hashers.BCryptSHA256PasswordHasher",
    "django.contrib.auth.hashers.ScryptPasswordHasher",
]


